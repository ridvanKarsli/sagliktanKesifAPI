"""Port'lar: alan katmanının dış dünyadan beklediği sözleşmeler (Protocol).

Somut uygulamalar `infrastructure/` altındadır. Arayüz Ayrımı İlkesi (ISP) gereği motor dört küçük port'a bölünmüştür:
analiz çalıştırma, sonuç okuma, hastalık kataloğu ve dış servisler. Kullanım senaryoları yalnızca ihtiyaç duydukları
port'u alır.
"""

from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Any, Callable, Dict, Iterable, List, Optional, Protocol, Tuple

from .entities import (
    AnalysisRun,
    Artifact,
    ArtifactKind,
    Candidate,
    CandidateFilter,
    Disease,
    Page,
    RunProgress,
    StoredFile,
    TokenClaims,
    User,
)

ProgressCallback = Callable[[RunProgress], None]


# ---------------- depolar ----------------

class UserRepository(Protocol):
    def get(self, user_id: str) -> Optional[User]: ...
    def get_by_email(self, email: str) -> Optional[User]: ...
    def get_by_subject(self, subject: str) -> Optional[User]: ...
    def add(self, user: User) -> User: ...
    def update(self, user: User) -> User: ...
    def list(self) -> List[User]: ...
    def count(self) -> int: ...


class DiseaseRepository(Protocol):
    def get(self, key: str) -> Optional[Disease]: ...
    def list(self, include_removed: bool = False) -> List[Disease]: ...
    def add(self, disease: Disease) -> Disease: ...
    def update(self, disease: Disease) -> Disease: ...


class AnalysisRunRepository(Protocol):
    def get(self, run_id: str) -> Optional[AnalysisRun]: ...
    def add(self, run: AnalysisRun) -> AnalysisRun: ...
    def update(self, run: AnalysisRun) -> AnalysisRun: ...
    def active_for(self, disease_key: str) -> Optional[AnalysisRun]: ...
    def list(self, disease_key: Optional[str] = None, limit: int = 50) -> List[AnalysisRun]: ...
    def queued(self) -> List[AnalysisRun]: ...
    def latest_for(self, disease_key: str) -> Optional[AnalysisRun]: ...


class CandidateRepository(Protocol):
    def replace_for_disease(self, disease_key: str, run_id: Optional[str], candidates: Iterable[Candidate]) -> int: ...
    def query(self, disease_key: str, flt: CandidateFilter, page: Page) -> Tuple[int, List[Candidate]]: ...
    def get(self, disease_key: str, chemical_id: str) -> Optional[Candidate]: ...
    def count_for(self, disease_key: str) -> int: ...
    def delete_for_disease(self, disease_key: str) -> int: ...


class ArtifactRepository(Protocol):
    def put(self, artifact: Artifact) -> Artifact: ...
    def get(self, disease_key: str, kind: ArtifactKind) -> Optional[Artifact]: ...
    def kinds_for(self, disease_key: str) -> List[ArtifactKind]: ...
    def delete_for_disease(self, disease_key: str) -> int: ...


class FileRepository(Protocol):
    """Motor çalışma dosyaları (blob). İçerik büyük olabilir; meta listesi ayrı okunur."""

    def list_meta(self, scope: str) -> List[StoredFile]: ...
    def get(self, path: str) -> Optional[StoredFile]: ...
    def put(self, file: StoredFile) -> None: ...
    def delete(self, path: str) -> None: ...
    def delete_scope(self, scope: str) -> int: ...


class UnitOfWork(Protocol):
    """Tek iş birimi = tek veritabanı hareketi. `with uow:` bloğu çıkışta otomatik geri alır; `commit()` açıkça çağrılır."""

    users: UserRepository
    diseases: DiseaseRepository
    runs: AnalysisRunRepository
    candidates: CandidateRepository
    artifacts: ArtifactRepository
    files: FileRepository

    def __enter__(self) -> UnitOfWork: ...
    def __exit__(self, exc_type, exc, tb) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...


UnitOfWorkFactory = Callable[[], UnitOfWork]


# ---------------- motor ----------------

class AnalysisEngine(Protocol):
    """Analiz çalıştırma. Uzun sürer; yalnızca worker sürecinden çağrılır."""

    def run(self, disease: Disease, steps: List[str], params: Dict[str, Any], options: Dict[str, Any],
            progress: ProgressCallback, log_path: Path) -> Dict[str, Any]: ...
    def rerank(self, disease: Disease, params: Dict[str, Any], cutoff: Optional[int]) -> Dict[str, Any]: ...
    def default_params(self) -> Dict[str, Any]: ...
    def validate_params(self, params: Dict[str, Any]) -> Dict[str, Any]: ...
    def status(self, disease_key: str) -> Dict[str, Any]: ...
    def is_network_error(self, exc: BaseException) -> bool: ...


class ResultReader(Protocol):
    """Motorun çalışma dizinindeki çıktılarını okur. Yalnızca `SyncResults` tarafından, sonuçları veritabanına
    aktarmak için kullanılır; API bu port'tan değil veritabanından okur."""

    def candidates(self, disease_key: str) -> List[Dict[str, Any]]: ...
    def evidence(self, disease_key: str, chemical_id: str) -> List[Dict[str, Any]]: ...
    def known_therapies(self, disease_key: str) -> List[Dict[str, Any]]: ...
    def backtest(self, disease_key: str) -> Dict[str, Any]: ...
    def tuning(self, disease_key: str) -> Dict[str, Any]: ...
    def bridges(self, disease_key: str) -> List[Dict[str, Any]]: ...
    def discovery(self, disease_key: str) -> Dict[str, Any]: ...
    def compare_row(self, key: str, label: str, summary: Dict[str, Any]) -> Dict[str, Any]: ...
    def default_fusion(self) -> Dict[str, Any]: ...
    def report_html(self, disease_key: str) -> Optional[str]: ...
    def log_tail(self, disease_key: str, tail: int) -> List[str]: ...


class DiseaseCatalog(Protocol):
    """Hastalık sözlüğü (MeSH) ve ad çözümleme."""

    def status(self) -> Dict[str, Any]: ...
    def build(self, progress: Callable[[str], None]) -> None: ...
    def search(self, query: str, limit: int) -> List[Dict[str, Any]]: ...
    def browse(self, query: str, category: str, offset: int, limit: int) -> Dict[str, Any]: ...
    def article_count(self, term: str, entries: List[str]) -> Dict[str, Any]: ...
    def resolve(self, name: str) -> List[Dict[str, Any]]: ...
    def build_query(self, mesh_term: str, name_en: str) -> str: ...
    def slugify(self, text: str) -> str: ...


class ExternalServices(Protocol):
    def health(self) -> List[Dict[str, Any]]: ...
    def drug_indications(self, chembl_id: str) -> List[Dict[str, Any]]: ...
    def pubmed_count(self, query: str) -> int: ...
    def estimate(self, disease: Disease, max_a: int) -> Dict[str, Any]: ...


class WorkspaceSync(Protocol):
    """Motorun çalışma dizini ↔ veritabanı eşitlemesi. Çalıştırma öncesi `prepare`, sonrası `save`."""

    def prepare(self, disease_key: Optional[str] = None) -> Dict[str, int]: ...
    def save(self, disease_key: Optional[str] = None) -> Dict[str, int]: ...
    def discard(self, disease_key: str) -> int: ...


# ---------------- kuyruk ----------------

class JobQueue(Protocol):
    def enqueue(self, run_id: str) -> None: ...
    def ping(self) -> bool: ...


# ---------------- kimlik ----------------

class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, password_hash: str) -> bool: ...


class TokenService(Protocol):
    def issue(self, user: User, token_type: str = "access") -> Tuple[str, datetime]: ...
    def decode(self, token: str) -> TokenClaims: ...


class Clock(Protocol):
    def now(self) -> datetime: ...
